-- A limited directory view is available to non-HR roles; it omits mobile and father_name.
create or replace view public.employee_directory
with (security_barrier = true)
as
  select id, employee_code, employee_name, designation, is_active
  from public.employees
  where is_active = true;

create table if not exists public.shift_assignments (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees(id) on delete restrict,
  work_date date not null,
  shift text not null check (shift in ('first', 'second', 'night', 'rest')),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (employee_id, work_date)
);

create table if not exists public.attendance (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees(id) on delete restrict,
  attendance_date date not null,
  status text not null check (status in ('Present', 'Absent', 'Late', 'Half day')),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (employee_id, attendance_date)
);

create table if not exists public.leave_requests (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees(id) on delete restrict,
  leave_type text not null check (leave_type in ('Annual', 'Sick', 'Casual', 'Unpaid', 'Other')),
  start_date date not null,
  end_date date not null,
  reason text not null default '',
  status text not null default 'Pending'
    check (status in ('Pending', 'Approved', 'Rejected', 'Cancelled')),
  submitted_by uuid references auth.users(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create table if not exists public.ppe_items (
  id uuid primary key default gen_random_uuid(),
  item_name text not null unique,
  opening_stock integer not null default 0 check (opening_stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.ppe_issues (
  id uuid primary key default gen_random_uuid(),
  employee_id uuid not null references public.employees(id) on delete restrict,
  item_id uuid not null references public.ppe_items(id) on delete restrict,
  issue_date date not null,
  quantity integer not null check (quantity > 0),
  issued_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (employee_id, item_id, issue_date)
);

create table if not exists public.ppe_stock_movements (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.ppe_items(id) on delete restrict,
  movement_type text not null check (movement_type in ('received', 'return')),
  quantity integer not null check (quantity > 0),
  movement_date date not null,
  employee_id uuid references public.employees(id) on delete restrict,
  note text not null default '',
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (movement_type <> 'return' or employee_id is not null)
);

