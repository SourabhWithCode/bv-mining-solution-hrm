create policy "profiles read self or HR" on public.user_profiles
  for select to authenticated
  using (id = (select auth.uid()) or public.has_any_role(array['admin', 'hr']));
create policy "profiles update by admin" on public.user_profiles
  for update to authenticated
  using (public.has_any_role(array['admin']))
  with check (public.has_any_role(array['admin']));

create policy "employees read authenticated roles" on public.employees
  for select to authenticated
  using (public.has_any_role(array['admin', 'hr']));
create policy "employees manage by HR" on public.employees
  for all to authenticated
  using (public.has_any_role(array['admin', 'hr']))
  with check (public.has_any_role(array['admin', 'hr']));

